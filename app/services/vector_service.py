"""
Vector Service
Handles vector storage and retrieval using Pinecone.

ARCHITECTURE NOTE:
  Embeddings are generated by OUR application using OpenAI text-embedding-3-small (1536 dims).
  Pinecone is used ONLY as a vector store — it does NOT generate embeddings.
  Therefore this service requires a standard Pinecone vector index (no document schema / no
  integrated embedding model). If your index was created with an integrated model in the
  Pinecone console, delete it and let this service auto-create a plain vector index, OR
  rename PINECONE_INDEX_NAME in .env to a new index name.
"""

from typing import List, Dict, Any
import logging
from pinecone.grpc import PineconeGRPC
from pinecone import ServerlessSpec
from app.config import settings

logger = logging.getLogger("rag_app.vector_service")

# Embedding dimension for OpenAI text-embedding-3-small
EMBEDDING_DIMENSION = 1536


class VectorService:
    """Service for vector operations using Pinecone."""

    def __init__(self, api_key: str | None = None):
        """
        Initialize the vector service with Pinecone.

        Args:
            api_key: Pinecone API key (optional, uses settings if not provided)
        """
        self.api_key = api_key or settings.PINECONE_API_KEY
        if not self.api_key:
            raise ValueError("Pinecone API key is required. Set PINECONE_API_KEY in .env file.")

        self.environment = settings.PINECONE_ENVIRONMENT
        self.index_name = settings.PINECONE_INDEX_NAME

        # Parse AWS region from environment string (e.g. "us-east-1-aws" → "us-east-1")
        env_parts = self.environment.split("-")
        # Drop trailing "aws"/"gcp"/"azure" suffix if present
        if env_parts and env_parts[-1] in ("aws", "gcp", "azure"):
            self._region = "-".join(env_parts[:-1])
            self._cloud = env_parts[-1]
        else:
            self._region = self.environment
            self._cloud = "aws"

        # Initialize Pinecone client with gRPC for better performance
        self.pc = PineconeGRPC(api_key=self.api_key)
        self.index = None
        self._has_document_schema = False  # Track if index has an integrated doc schema

    def _check_index_schema(self, index_description) -> bool:
        """
        Returns True if the index has a document / integrated-embedding schema.
        Such indexes require the Pinecone Documents API and cannot accept raw vector upserts.

        Detection: Pinecone document-schema indexes have named fields (e.g. 'chunk_text',
        'title') with an 'embed' config inside spec.serverless.schema.fields.
        A plain vector index only has system fields '_values' and '_sparse_values'.
        """
        try:
            # Top-level embed attribute (older SDK format)
            if getattr(index_description, "embed", None) is not None:
                return True

            # Check spec.serverless.schema.fields for user-defined embedded fields
            spec = getattr(index_description, "spec", None)
            if spec:
                serverless = getattr(spec, "serverless", None)
                if serverless:
                    schema = getattr(serverless, "schema", None)
                    if isinstance(schema, dict):
                        fields = schema.get("fields", {})
                    elif schema:
                        fields = getattr(schema, "fields", {}) or {}
                    else:
                        fields = {}

                    # System-only fields: '_values', '_sparse_values'
                    # If any user-defined field has an 'embed' config → document schema
                    for field_name, field_config in fields.items():
                        if field_name.startswith("_"):
                            continue  # skip system fields
                        if isinstance(field_config, dict):
                            if field_config.get("embed") is not None:
                                logger.warning(
                                    f"Index field '{field_name}' has an integrated embed model — "
                                    "this index uses a document schema."
                                )
                                return True
                        else:
                            embed_val = getattr(field_config, "embed", None)
                            if embed_val is not None:
                                logger.warning(
                                    f"Index field '{field_name}' has an integrated embed model — "
                                    "this index uses a document schema."
                                )
                                return True
        except Exception as exc:
            logger.debug(f"_check_index_schema inspection error (non-fatal): {exc}")
        return False

    def connect_to_index(self):
        """
        Connect to the Pinecone index.
        Creates a standard vector index if the named index does not yet exist.

        IMPORTANT: If the index already exists but has a document schema (integrated
        embedding), this method raises a clear error explaining the fix required.
        """
        try:
            # Check if index exists
            existing_indexes = self.pc.list_indexes()
            index_names = [idx["name"] for idx in existing_indexes]

            if self.index_name not in index_names:
                # Create a plain vector index (no integrated embedding model)
                logger.info(
                    f"Creating Pinecone vector index: {self.index_name} "
                    f"(dim={EMBEDDING_DIMENSION}, metric=cosine, "
                    f"cloud={self._cloud}, region={self._region})"
                )
                self.pc.create_index(
                    name=self.index_name,
                    dimension=EMBEDDING_DIMENSION,
                    metric="cosine",
                    spec=ServerlessSpec(
                        cloud=self._cloud,
                        region=self._region,
                    ),
                )
                logger.info(f"Index '{self.index_name}' created successfully")
            else:
                # Index already exists — validate it is a plain vector index
                index_description = self.pc.describe_index(name=self.index_name)
                if self._check_index_schema(index_description):
                    raise Exception(
                        f"The Pinecone index '{self.index_name}' was created with an integrated "
                        "embedding / document schema. This app generates its own embeddings via "
                        "OpenAI and requires a plain vector index.\n\n"
                        "FIX: Delete the index in the Pinecone console (or rename "
                        "PINECONE_INDEX_NAME in .env to a new name) and restart the app. "
                        "The app will then auto-create a compatible standard vector index."
                    )

            # Connect to the index
            index_description = self.pc.describe_index(name=self.index_name)
            self.index = self.pc.Index(host=index_description.host)
            logger.info(f"Connected to Pinecone index: {self.index_name}")

        except Exception as e:
            raise Exception(f"Failed to connect to Pinecone index: {str(e)}")

    def add_documents(
        self,
        chunks: List[Dict[str, Any]],
        embeddings: List[List[float]],
        filename: str,
        namespace: str = "default"
    ):
        """
        Store document chunks with their embeddings in Pinecone.

        Embeddings are generated by OUR application (OpenAI text-embedding-3-small).
        Pinecone stores them as plain float vectors — no integrated model is involved.

        Args:
            chunks: List of chunk dictionaries with text and metadata
            embeddings: List of embedding vectors corresponding to chunks
            filename: Source filename for metadata
            namespace: Pinecone namespace for organization (default: "default")

        Raises:
            Exception: If upsert fails
        """
        if not self.index:
            self.connect_to_index()

        if len(chunks) != len(embeddings):
            raise ValueError(f"Mismatch: {len(chunks)} chunks but {len(embeddings)} embeddings")

        try:
            import json

            # Build vector dicts (Pinecone SDK v5+ prefers dicts over tuples)
            vectors_to_upsert = []
            for chunk, embedding in zip(chunks, embeddings):
                vector_id = f"{filename}_{chunk['chunk_index']}"
                metadata = {
                    "filename": filename,
                    "chunk_index": chunk["chunk_index"],
                    "token_count": chunk["token_count"],
                    "text": chunk["text"][:1000],  # Pinecone metadata size limit
                    "start_char": chunk.get("start_char", 0),
                    "end_char": chunk.get("end_char", 0),
                    "headings": json.dumps(chunk.get("headings", [])),
                    "page_numbers": json.dumps(chunk.get("page_numbers", [])),
                    "has_context": len(chunk.get("headings", [])) > 0,
                }
                vectors_to_upsert.append({
                    "id": vector_id,
                    "values": embedding,
                    "metadata": metadata,
                })

            # Upsert in batches of 100 (Pinecone recommended batch size)
            batch_size = 100
            for i in range(0, len(vectors_to_upsert), batch_size):
                batch = vectors_to_upsert[i:i + batch_size]
                self.index.upsert(
                    vectors=batch,
                    namespace=namespace,
                )
                logger.debug(
                    f"Upserted batch {i // batch_size + 1} "
                    f"({len(batch)} vectors, namespace={namespace!r})"
                )

            logger.info(f"Successfully upserted {len(vectors_to_upsert)} vectors to Pinecone")

        except Exception as e:
            raise Exception(f"Failed to add documents to Pinecone: {str(e)}")

    async def search(
        self,
        query_embedding: List[float],
        top_k: int = 3,
        namespace: str = "default",
        filter_dict: Dict[str, Any] | None = None
    ) -> Dict[str, Any]:
        """
        Search for similar vectors in Pinecone.

        Args:
            query_embedding: Query vector
            top_k: Number of results to return (default: 3)
            namespace: Pinecone namespace to search (default: "default")
            filter_dict: Optional metadata filter

        Returns:
            Dictionary with search results:
                - query: The query vector (first 5 dims for reference)
                - chunks: List of matched chunks with metadata and scores
                - total_found: Number of results returned
        """
        if not self.index:
            self.connect_to_index()

        try:
            # Query Pinecone
            results = self.index.query(
                vector=query_embedding,
                top_k=top_k,
                include_metadata=True,
                namespace=namespace,
                filter=filter_dict
            )

            # Format results
            chunks = []
            for match in results['matches']:
                chunks.append({
                    'id': match['id'],
                    'score': match['score'],
                    'text': match['metadata'].get('text', ''),
                    'metadata': {
                        'filename': match['metadata'].get('filename', ''),
                        'chunk_index': match['metadata'].get('chunk_index', 0),
                        'token_count': match['metadata'].get('token_count', 0),
                    }
                })

            return {
                'query_preview': query_embedding[:5],  # Just first 5 dims for reference
                'chunks': chunks,
                'total_found': len(chunks)
            }

        except Exception as e:
            raise Exception(f"Failed to search Pinecone: {str(e)}")

    def get_index_stats(self, namespace: str = "default") -> Dict[str, Any]:
        """
        Get statistics about the Pinecone index.

        Args:
            namespace: Namespace to get stats for

        Returns:
            Dictionary with index statistics
        """
        if not self.index:
            self.connect_to_index()

        try:
            stats = self.index.describe_index_stats()
            return {
                "total_vector_count": stats.get('total_vector_count', 0),
                "dimension": stats.get('dimension', 0),
                "namespaces": stats.get('namespaces', {}),
            }
        except Exception as e:
            raise Exception(f"Failed to get index stats: {str(e)}")

    def delete_by_filename(self, filename: str, namespace: str = "default"):
        """
        Delete all vectors associated with a filename.

        Args:
            filename: Filename to delete
            namespace: Namespace containing the vectors
        """
        if not self.index:
            self.connect_to_index()

        try:
            # Delete using metadata filter
            self.index.delete(
                filter={"filename": {"$eq": filename}},
                namespace=namespace
            )
            logger.info(f"Deleted all vectors for filename: {filename}")

        except Exception as e:
            raise Exception(f"Failed to delete vectors: {str(e)}")

    def delete_all_vectors(self, namespace: str = "default") -> Dict[str, Any]:
        """
        Delete all vectors from a Pinecone namespace.

        WARNING: This operation cannot be undone!

        Args:
            namespace: The namespace to clear (default: "default").
                      Use "*" to clear all namespaces.

        Returns:
            Dictionary with deletion status:
            {
                'status': 'success' | 'failed',
                'namespaces_cleared': [list of namespace names],
                'message': str
            }

        Raises:
            Exception if delete operation fails
        """
        if not self.index:
            self.connect_to_index()

        try:
            if namespace == "*":
                # Clear all namespaces
                stats = self.get_index_stats()
                namespaces_to_clear = list(stats.get('namespaces', {}).keys())

                if not namespaces_to_clear:
                    logger.info("No namespaces found to clear")
                    return {
                        'status': 'success',
                        'namespaces_cleared': [],
                        'message': 'No vectors found in index'
                    }

                # Delete all vectors from each namespace
                for ns in namespaces_to_clear:
                    logger.warning(f"Deleting ALL vectors from namespace: {ns}")
                    self.index.delete(delete_all=True, namespace=ns)

                logger.info(f"Cleared all vectors from {len(namespaces_to_clear)} namespaces")

                return {
                    'status': 'success',
                    'namespaces_cleared': namespaces_to_clear,
                    'message': f'Deleted all vectors from {len(namespaces_to_clear)} namespaces'
                }
            else:
                # Clear specific namespace
                logger.warning(f"Deleting ALL vectors from namespace: {namespace}")
                self.index.delete(delete_all=True, namespace=namespace)

                logger.info(f"Cleared all vectors from namespace: {namespace}")

                return {
                    'status': 'success',
                    'namespaces_cleared': [namespace],
                    'message': f'Deleted all vectors from namespace "{namespace}"'
                }

        except Exception as e:
            logger.error(f"Failed to delete all vectors: {e}")
            return {
                'status': 'failed',
                'namespaces_cleared': [],
                'message': f'Failed to delete vectors: {str(e)}'
            }
